// ApplyDocument applies the provided Document to the remote document identified
// by docID. This is a stub that simulates an update; the real implementation
// will call Google Docs API to patch the document contents.
func ApplyDocument(authMode, docID string, doc *Document) error {
	if docID == "" {
		return fmt.Errorf("missing doc id")
	}
	// Prefer service account credentials (GOOGLE_APPLICATION_CREDENTIALS)
	creds := os.Getenv("GOOGLE_APPLICATION_CREDENTIALS")
	ctx := context.Background()
	client, err := gauth.NewHTTPClient(ctx, "service", creds)
	if err != nil {
		return fmt.Errorf("creating google http client: %w", err)
	}
	svc, err := docs.NewService(ctx, option.WithHTTPClient(client))
	if err != nil {
		return fmt.Errorf("creating docs service: %w", err)
	}

	// Convert the provided Document to markdown text and write it into the
	// document body as plain text. This is a pragmatic, minimal update for
	// integration tests; a richer mapping to structural Google Docs elements
	// can be implemented later.
	mdText, err := DocumentToMarkdown(doc)
	if err != nil {
		return fmt.Errorf("convert doc to markdown: %w", err)
	}

	// Fetch remote document to determine current content end index.
	remote, err := svc.Documents.Get(docID).Do()
	if err != nil {
		return fmt.Errorf("fetching remote document: %w", err)
	}
	endIndex := int64(1)
	if remote.Body != nil && len(remote.Body.Content) > 0 {
		// Use the EndIndex of the last content element if present
		last := remote.Body.Content[len(remote.Body.Content)-1]
		if last.EndIndex != 0 {
			endIndex = last.EndIndex
		}
	}
	// The Docs API disallows delete ranges that include the final trailing
	// newline character. If endIndex points to the document end, reduce it by
	// one so the delete range doesn't include that final newline.
	if endIndex > 1 {
		endIndex = endIndex - 1
	}

	// Build structured requests from the Document model.
	requests, err := buildDocsRequests(mdText, doc)
	if err != nil {
		return fmt.Errorf("building docs requests: %w", err)
	}

	// Prepend delete of existing content.
	delReq := &docs.Request{DeleteContentRange: &docs.DeleteContentRangeRequest{Range: &docs.Range{StartIndex: 1, EndIndex: endIndex}}}
	all := append([]*docs.Request{delReq}, requests...)

	_, err = svc.Documents.BatchUpdate(docID, &docs.BatchUpdateDocumentRequest{Requests: all}).Do()
	if err != nil {
		return fmt.Errorf("batch update failed: %w", err)
	}
	return nil
}

// buildDocsRequests converts a markdown string and Document into a sequence of
// Google Docs Requests that insert text and apply simple heading styles.
func buildDocsRequests(mdText string, doc *Document) ([]*docs.Request, error) {
	var reqs []*docs.Request
	_ = mdText
	// We'll insert each element's text and, for headings, add an UpdateParagraphStyle request.
	var currIndex int64 = 1

	appendInsert := func(text string) int64 {
		// create InsertText request at current index
		r := &docs.Request{InsertText: &docs.InsertTextRequest{Text: text, Location: &docs.Location{Index: currIndex}}}
		reqs = append(reqs, r)
		length := int64(len(text))
		currIndex += length
		return currIndex - length
	}
	appendTextWithSpans := func(prefix, txt string) {
		clean, spans := parseInline(txt)
		start := appendInsert(prefix + clean + "\n")
		for _, sp := range spans {
			s := start + int64(len(prefix)) + int64(sp.Offset)
			eidx := s + int64(sp.Length)
			switch sp.Kind {
			case "bold":
				reqs = append(reqs, &docs.Request{UpdateTextStyle: &docs.UpdateTextStyleRequest{
					Range:     &docs.Range{StartIndex: s, EndIndex: eidx},
					TextStyle: &docs.TextStyle{Bold: true},
					Fields:    "bold",
				}})
			case "italic":
				reqs = append(reqs, &docs.Request{UpdateTextStyle: &docs.UpdateTextStyleRequest{
					Range:     &docs.Range{StartIndex: s, EndIndex: eidx},
					TextStyle: &docs.TextStyle{Italic: true},
					Fields:    "italic",
				}})
			case "code":
				reqs = append(reqs, &docs.Request{UpdateTextStyle: &docs.UpdateTextStyleRequest{
					Range:     &docs.Range{StartIndex: s, EndIndex: eidx},
					TextStyle: &docs.TextStyle{WeightedFontFamily: &docs.WeightedFontFamily{FontFamily: "Courier New"}},
					Fields:    "weightedFontFamily",
				}})
			case "link":
				reqs = append(reqs, &docs.Request{UpdateTextStyle: &docs.UpdateTextStyleRequest{
					Range:     &docs.Range{StartIndex: s, EndIndex: eidx},
					TextStyle: &docs.TextStyle{Link: &docs.Link{Url: sp.Data}},
					Fields:    "link",
				}})
			}
		}
	}

	for i := 0; i < len(doc.Body); i++ {
		e := doc.Body[i]
		switch v := e.(type) {
		case Heading:
			// Insert heading text + newline
			start := appendInsert(v.Text + "\n")
			end := currIndex
			// Map level to NamedStyleType
			var nst string
			switch v.Level {
			case 1:
				nst = "HEADING_1"
			case 2:
				nst = "HEADING_2"
			case 3:
				nst = "HEADING_3"
			case 4:
				nst = "HEADING_4"
			case 5:
				nst = "HEADING_5"
			default:
				nst = "HEADING_6"
			}
			reqs = append(reqs, &docs.Request{UpdateParagraphStyle: &docs.UpdateParagraphStyleRequest{
				Range:          &docs.Range{StartIndex: start, EndIndex: end},
				ParagraphStyle: &docs.ParagraphStyle{NamedStyleType: nst},
				Fields:         "namedStyleType",
			}})
		case Paragraph:
			appendTextWithSpans("", v.Text)
		case ListItem:
			start := currIndex
			appendTextWithSpans(strings.Repeat("\t", v.Level), v.Text)
			for j := i + 1; j < len(doc.Body); j++ {
				next, ok := doc.Body[j].(ListItem)
				if !ok || next.Ordered != v.Ordered {
					break
				}
				appendTextWithSpans(strings.Repeat("\t", next.Level), next.Text)
				i = j
			}
			end := currIndex
			preset := "BULLET_DISC_CIRCLE"
			if v.Ordered {
				preset = "NUMBERED_DECIMAL"
			}
			reqs = append(reqs, &docs.Request{CreateParagraphBullets: &docs.CreateParagraphBulletsRequest{
				Range:        &docs.Range{StartIndex: start, EndIndex: end},
				BulletPreset: preset,
			}})
		case CodeBlock:
			start := appendInsert(v.Code + "\n")
			end := currIndex
			reqs = append(reqs, &docs.Request{UpdateTextStyle: &docs.UpdateTextStyleRequest{
				Range:     &docs.Range{StartIndex: start, EndIndex: end},
				TextStyle: &docs.TextStyle{WeightedFontFamily: &docs.WeightedFontFamily{FontFamily: "Courier New"}},
				Fields:    "weightedFontFamily",
			}})
			appendInsert("\n")
		case Image:
			start := appendInsert("\n")
			reqs = append(reqs, &docs.Request{InsertInlineImage: &docs.InsertInlineImageRequest{
				Uri:      v.URL,
				Location: &docs.Location{Index: start},
			}})
		default:
			// ignore
		}
	}
	return reqs, nil
}

type inlineSpan struct {
	Offset int
	Length int
	Kind   string // "bold", "italic", "code", "link"
	Data   string // for link: URL
}

type inlineStyleState struct {
	bold   bool
	italic bool
	code   bool
	link   string
}

// parseInline parses inline markdown using Goldmark and returns cleaned text
// plus style spans to apply in Google Docs.
func parseInline(s string) (string, []inlineSpan) {
	parser := goldmark.DefaultParser()
	root := parser.Parse(text.NewReader([]byte(s)))
	source := []byte(s)
	var out strings.Builder
	var spans []inlineSpan

	addText := func(val string, st inlineStyleState) {
		if val == "" {
			return
		}
		off := out.Len()
		out.WriteString(val)
		length := len(val)
		if st.bold {
			spans = append(spans, inlineSpan{Offset: off, Length: length, Kind: "bold"})
		}
		if st.italic {
			spans = append(spans, inlineSpan{Offset: off, Length: length, Kind: "italic"})
		}
		if st.code {
			spans = append(spans, inlineSpan{Offset: off, Length: length, Kind: "code"})
		}
		if st.link != "" {
			spans = append(spans, inlineSpan{Offset: off, Length: length, Kind: "link", Data: st.link})
		}
	}

	var walkInline func(n ast.Node, st inlineStyleState)
	walkInline = func(n ast.Node, st inlineStyleState) {
		for c := n.FirstChild(); c != nil; c = c.NextSibling() {
			switch v := c.(type) {
			case *ast.Text:
				addText(string(v.Segment.Value(source)), st)
				if v.SoftLineBreak() || v.HardLineBreak() {
					addText(" ", st)
				}
			case *ast.String:
				addText(string(v.Value), st)
			case *ast.Emphasis:
				next := st
				if v.Level >= 2 {
					next.bold = true
				} else {
					next.italic = true
				}
				walkInline(v, next)
			case *ast.CodeSpan:
				next := st
				next.code = true
				addText(string(v.Text(source)), next)
			case *ast.Link:
				next := st
				next.link = string(v.Destination)
				walkInline(v, next)
			default:
				walkInline(v, st)
			}
		}
	}

	for n := root.FirstChild(); n != nil; n = n.NextSibling() {
		walkInline(n, inlineStyleState{})
	}

	return out.String(), spans
}
